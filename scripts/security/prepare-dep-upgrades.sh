#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$root"

BR=chore/upgrade-dependencies

echo "Preparing dependency upgrades on branch $BR"

if ! command -v npx >/dev/null 2>&1; then
  echo "npx not found" >&2
  exit 2
fi

echo "Updating package.json with npm-check-updates (ncu)"
npx npm-check-updates -u

echo "Installing updated dependencies (this updates package-lock.json)"
npm install

echo "Running tests"
npm test || echo "Tests failed; inspect locally before merging"

git checkout -B "$BR"
git add package.json package-lock.json
git commit -m "chore(deps): upgrade dependencies with npm-check-updates" || echo "No changes to commit"
git push -u origin "$BR"

if command -v gh >/dev/null 2>&1; then
  gh pr create --title "chore: upgrade dependencies" \
    --body "Automated dependency upgrades generated by npm-check-updates. Run CI and verify tests." \
    --base main --head "$BR" --draft || echo "gh pr create failed"
else
  echo "Branch pushed. Create PR for $BR in GitHub UI or install gh CLI to automate PR creation."
fi

echo "Done."
